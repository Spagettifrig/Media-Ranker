import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * The website build: the same React app as the desktop one, with
 * src/web/api.js standing in for the Electron bridge. Output goes to
 * dist-web/, a plain folder of static files any static host can serve.
 *
 *   npm run dev:web      local dev server on http://localhost:5174
 *   npm run build:web    production build into dist-web/
 */

const root = path.dirname(fileURLToPath(import.meta.url));
const electronDir = path.join(root, 'electron');

/**
 * electron/supabase.js and electron/steam.js are shared with the desktop app
 * as they are. Two of their imports only make sense under Node, so the web
 * build points those at browser versions instead:
 *   ./auth-storage.js  - the session file  -> localStorage
 *   node:crypto        - randomUUID        -> crypto.randomUUID
 * Anything reaching for `electron` itself is a mistake, and fails the build.
 */
function webBridge() {
  return {
    name: 'game-ranker-web-bridge',
    enforce: 'pre',
    resolveId(source, importer) {
      if (!importer || !importer.startsWith(electronDir)) return null;
      if (source === './auth-storage.js') return path.join(root, 'src/web/auth-storage.js');
      if (source === 'node:crypto') return path.join(root, 'src/web/shims/node-crypto.js');
      if (source === 'electron' || source.startsWith('node:')) {
        this.error(`${path.relative(root, importer)} imports "${source}", which the website cannot use.`);
      }
      return null;
    },
  };
}

/**
 * The production build bundles electron/'s CommonJS on its own, but the dev
 * server serves files as native ES modules and a browser has no `require`.
 * Those files only use two shapes - `const ... = require('x');` and one
 * `module.exports = ...` - so in dev they are rewritten into imports and a
 * default export. `.default ?? namespace` covers both kinds of target: a
 * rewritten sibling (default only) and a real ES module (named only).
 */
function devCommonJs() {
  return {
    name: 'game-ranker-dev-commonjs',
    apply: 'serve',
    enforce: 'pre',
    transform(code, id) {
      if (!id.startsWith(electronDir) || !id.endsWith('.js')) return null;
      let count = 0;
      const imports = [];
      const body = code
        .replace(/^const (.+?) = require\((['"])(.+?)\2\);$/gm, (_match, binding, _quote, source) => {
          const name = `__cjs${count++}`;
          imports.push(`import * as ${name} from ${JSON.stringify(source)};`);
          return `const ${binding} = ${name}.default ?? ${name};`;
        })
        .replace(/^module\.exports = /m, 'export default ');
      if (/\brequire\(/.test(body)) this.error(`${id} has a require() the dev rewrite does not handle.`);
      return { code: `${imports.join('\n')}\n${body}`, map: null };
    },
  };
}

/**
 * Emits sw.js, the service worker that makes the site work offline and
 * installable. Generated rather than hand-written so it can list the exact
 * files of this build: every deploy gets a new cache, and the old one is
 * dropped as soon as the new worker takes over.
 *
 * What it caches is only the app itself, all same-origin. Supabase, the
 * catalog and cover art are never cached here - account data must always be
 * live, and the browser's own HTTP cache already handles the images.
 */
function serviceWorker() {
  return {
    name: 'game-ranker-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = [
        './',
        ...Object.keys(bundle).filter((name) => name !== 'index.html'),
        'manifest.webmanifest',
        'icons/icon-192.png',
        'icons/icon-512.png',
        'icons/apple-touch-icon.png',
      ];
      const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: SERVICE_WORKER.replace('__VERSION__', version).replace('__FILES__', JSON.stringify(files)),
      });
    },
  };
}

const SERVICE_WORKER = `// Generated by vite.web.config.mjs - edit it there.
const CACHE = 'game-ranker-__VERSION__';
const FILES = __FILES__;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('game-ranker-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  // Pages: the network first, so a new deploy shows up on the next visit;
  // the cached app when there is no connection.
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('./', { cacheName: CACHE })));
    return;
  }

  // Build files have content hashes in their names, so a cached copy is never stale.
  event.respondWith(caches.match(request, { cacheName: CACHE }).then((hit) => hit || fetch(request)));
});
`;

export default defineConfig({
  root: path.join(root, 'web'),
  publicDir: path.join(root, 'web/public'),
  // Relative, so the site works from a domain root or a sub-path (GitHub Pages).
  base: './',
  plugins: [webBridge(), devCommonJs(), react(), serviceWorker()],
  server: {
    port: 5174,
    strictPort: true,
    host: '127.0.0.1',
    fs: { allow: [root] },
  },
  preview: { port: 4174, strictPort: true, host: '127.0.0.1' },
  build: {
    outDir: path.join(root, 'dist-web'),
    emptyOutDir: true,
    chunkSizeWarningLimit: 1200,
  },
});
